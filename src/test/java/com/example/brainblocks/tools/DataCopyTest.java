package com.example.brainblocks.tools;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * 2026-11-14 (Shir: "move all my data" + "a nightly backup"): a copy and a backup file hold exactly what
 * the source held (booleans, times, Hebrew text, nulls), old tables / columns stay behind, a target with
 * data is never overwritten without --replace, and new rows get fresh ids after the copy.
 */
class DataCopyTest {

    @TempDir Path dir;

    static Connection db(String name, String mode) throws Exception {
        Connection c = DriverManager.getConnection("jdbc:h2:mem:" + name + ";MODE=" + mode + ";DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
        c.setAutoCommit(false);
        return c;
    }

    static void schema(Connection c, boolean old) throws Exception {
        try (Statement s = c.createStatement()) {
            s.execute("create table learn_profile (id bigint generated by default as identity primary key, name varchar(60), "
                    + "admin boolean not null, created_at timestamp(6), coins integer, score double precision"
                    + (old ? ", old_column varchar(10)" : "") + ")");
            s.execute("create table learn_answer (id bigint generated by default as identity primary key, profile_id bigint, "
                    + "correct boolean, text varchar(400))");
            if (old) s.execute("create table race_rooms (id bigint primary key)");
        }
        c.commit();
    }

    static long count(Connection c, String sql) throws Exception {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            rs.next();
            return rs.getLong(1);
        }
    }

    @Test
    void copyDumpAndLoadKeepEverything() throws Exception {
        Connection from = db("src", "MySQL");
        schema(from, true);
        try (Statement s = from.createStatement()) {
            s.execute("insert into learn_profile (id, name, admin, created_at, coins, score, old_column) values "
                    + "(5, 'שיר', true, '2026-11-14 13:10:00.123456', 1000000, 2.5, 'x'), "
                    + "(9, 'אדל', false, null, null, null, null)");
            s.execute("insert into learn_answer (id, profile_id, correct, text) values (3, 9, true, '38 + 27 = ?'), (4, 9, false, null)");
            s.execute("insert into race_rooms values (1)");
        }
        from.commit();

        Connection to = db("dst", "PostgreSQL");
        schema(to, false);
        assertThat(DataCopy.copy(from, to, false)).isZero();
        assertThat(count(to, "select count(*) from learn_profile")).isEqualTo(2);
        assertThat(count(to, "select count(*) from learn_profile where name = 'שיר' and admin and coins = 1000000")).isEqualTo(1);
        // a new row after the copy gets a free id (not 1, which may be taken)
        try (Statement s = to.createStatement()) {
            s.execute("insert into learn_profile (name, admin) values ('חדש', false)");
        }
        to.commit();
        assertThat(count(to, "select max(id) from learn_profile")).isEqualTo(10);

        // a target with data is refused without --replace, and nothing changes
        assertThatThrownBy(() -> DataCopy.copy(from, to, false)).hasMessageContaining("already has data");
        assertThat(count(to, "select count(*) from learn_profile")).isEqualTo(3);
        assertThat(DataCopy.copy(from, to, true)).isZero();
        assertThat(count(to, "select count(*) from learn_profile")).isEqualTo(2);

        // the nightly backup: database -> file -> another database, identical
        Path zip = dir.resolve("backup.zip");
        assertThat(DataCopy.dump(to, zip)).isZero();
        assertThat(Files.size(zip)).isPositive();
        Connection back = db("back", "PostgreSQL");
        schema(back, false);
        assertThat(DataCopy.load(zip, back, false)).isZero();
        assertThat(DataCopy.fingerprints(back)).isEqualTo(DataCopy.fingerprints(to));
        assertThat(count(back, "select count(*) from learn_answer where correct")).isEqualTo(1);
    }
}
